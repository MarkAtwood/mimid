#!/usr/bin/env python3
"""CDDL oracle for mimi-content-10 (T7), run outside cargo test.

Validates CBOR against the WG CDDL vendored in ../fixtures/wg-10/ with the
Ruby `cddl` tool (an implementation independent of this crate):

- the 14 WG mimiContent examples against mimi-content.cddl;
- implied-original.cbor against implied.cddl;
- t6-message.cbor, the T6 unknown-extension message;
- a minimal valid message, and one-rule mutations of it that must fail.

Encoder output: tests/encode_wg.rs asserts the encoder's output for every
hand-built struct is byte-identical to its WG example, and
tests/extensions.rs asserts the same for the T6 message and
t6-message.cbor's bytes. Validating those bytes validates the encoder's
output.

Usage: CDDL=/path/to/cddl python3 -I cddl_check.py > cddl_check.out
CDDL defaults to `cddl` on PATH. Exits 1 if any verdict differs from the
expected one. Output: one line per case, "VALID<TAB><case>" or
"INVALID<TAB><case>". Standard library only; offline.
"""

import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
WG = HERE.parent / "fixtures" / "wg-10"
CONTENT_CDDL = WG / "mimi-content.cddl"
IMPLIED_CDDL = WG / "implied.cddl"

WG_EXAMPLES = [
    "attachment",
    "conferencing",
    "delete",
    "edit",
    "expiring",
    "mention",
    "mention-html",
    "multipart-1",
    "multipart-2",
    "multipart-3",
    "original",
    "reaction",
    "reply",
    "unlike",
]

SALT = "50" + "00" * 16  # salt: bstr(16), all zero
NULL_PART = "83016000"  # [1 render, "" language, 0 nullpart]


def message(
    salt=SALT,
    replaces="f6",  # null
    topic="40",  # bstr(0)
    expires="f6",  # null
    reply="f6",  # null
    ext="a0",  # map(0)
    part=NULL_PART,
    head="87",  # array(7)
):
    """Hex of a mimiContent; each argument replaces one field's encoding."""
    return head + salt + replaces + topic + expires + reply + ext + part


# (case, hex, expected valid). Each invalid case breaks one rule of
# Appendix A.1 in the valid base message.
SYNTHETIC = [
    ("minimal message", message(), True),
    ("salt is bstr(15)", message(salt="4f" + "00" * 15), False),
    ("replaces is bstr(31)", message(replaces="581f" + "00" * 31), False),
    # [false absolute, 2^32]: time is uint .size 4.
    ("expiration time 2^32", message(expires="82f41b0000000100000000"), False),
    # {1: 1}: senderUri must be tstr.
    ("senderUri is an integer", message(ext="a10101"), False),
    # {"": 1}: name = tstr .size (1..255).
    ("extension name is empty text", message(ext="a16001"), False),
    # [256, "", 0]: dispositions stop at 255.
    ("disposition 256", message(part="831901006000"), False),
    ("language is an integer", message(part="83010000"), False),
    ("cardinality 4", message(part="83016004"), False),
    # [1, "", 1, ""]: SinglePart without content.
    ("single part without content", message(part="8401600160"), False),
    # [1, "", 3 multi, 0 chooseOne, [one NestedPart]]: parts is 2*.
    ("multipart with one part", message(part="850160030081" + NULL_PART), False),
    # [1, "", 3 multi, 3, [two NestedParts]]: partSemantics is 0..2.
    ("partSemantics 3", message(part="850160030382" + NULL_PART * 2), False),
    ("eight top-level elements", message(head="88") + "f6", False),
    ("top level is a map", "a0", False),
]


def validate(tool, cddl, path):
    result = subprocess.run(
        [tool, str(cddl), "validate", str(path)], capture_output=True, text=True
    )
    if result.returncode not in (0, 1):
        sys.exit(f"{tool} exited {result.returncode}: {result.stderr.strip()}")
    return result.returncode == 0


def main():
    tool = os.environ.get("CDDL") or shutil.which("cddl")
    if not tool:
        sys.exit("cddl tool not found; set CDDL or put it on PATH")

    cases = [(name, CONTENT_CDDL, WG / f"{name}.cbor", True) for name in WG_EXAMPLES]
    cases.append(("implied-original", IMPLIED_CDDL, WG / "implied-original.cbor", True))
    cases.append(("t6-message", CONTENT_CDDL, HERE / "t6-message.cbor", True))

    failures = 0
    print("# Generated by cddl_check.py; do not edit by hand.")
    print("# Format: VALID|INVALID <TAB> case.")
    with tempfile.TemporaryDirectory() as tmp:
        for i, (name, hex_bytes, expected) in enumerate(SYNTHETIC):
            path = pathlib.Path(tmp) / f"case{i}.cbor"
            path.write_bytes(bytes.fromhex(hex_bytes))
            cases.append((name, CONTENT_CDDL, path, expected))
        for name, cddl, path, expected in cases:
            valid = validate(tool, cddl, path)
            print(f"{'VALID' if valid else 'INVALID'}\t{name}")
            if valid != expected:
                failures += 1
                print(f"MISMATCH: {name}: expected valid={expected}", file=sys.stderr)
    if failures:
        sys.exit(1)


if __name__ == "__main__":
    main()
